// Extract design logos and brand SVGs into the app. Usage: node extract-assets.js <v7 split dir> <app dir>
const fs = require("fs"), path = require("path"), vm = require("vm");
const [src, app] = process.argv.slice(2);
const logosJs = fs.readFileSync(path.join(src, "shared__logos.js"), "utf8");
const ctx = { window: {} }; vm.createContext(ctx); vm.runInContext(logosJs, ctx);
const LOGOS = ctx.window.LOGOS;
const out = path.join(app, "assets", "logos"); fs.mkdirSync(out, { recursive: true });
const png = [], svg = {};
for (const [k, uri] of Object.entries(LOGOS)) {
  const m = uri.match(/^data:image\/([a-z+]+)(;base64)?,(.*)$/s);
  if (!m) throw new Error("bad " + k);
  const body = m[2] ? Buffer.from(m[3], "base64") : Buffer.from(decodeURIComponent(m[3]));
  if (m[1] === "png") { fs.writeFileSync(path.join(out, k + ".png"), body); png.push(k); }
  else svg[k] = body.toString("utf8");
}
let ts = "// Generated from the design's shared/logos.js by extract-assets.js. Do not edit by hand.\n\n";
ts += "export const LOGO_PNG = {\n" + png.map(k => `  ${JSON.stringify(k)}: require("../../assets/logos/${k}.png"),`).join("\n") + "\n} as const;\n\n";
ts += "export const LOGO_SVG: Record<string, string> = {\n" + Object.entries(svg).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n") + "\n};\n";
fs.mkdirSync(path.join(app, "src", "generated"), { recursive: true });
fs.writeFileSync(path.join(app, "src", "generated", "logos.ts"), ts);
// brand: Vanna mark shape and wordmark
const core = fs.readFileSync(path.join(src, "core.js"), "utf8");
const shape = core.match(/const VANNA_SHAPE = '([^']+)'/)[1];
const wm = core.match(/const wordmark = [^`]*`(<svg[\s\S]*?<\/svg>)`/)[1];
const wmBody = wm.match(/<g fill="\$\{color\}" fill-rule="evenodd">([\s\S]*?)<\/g>/)[1];
let b = "// Vanna brand shapes from the design (core.js VANNA_SHAPE, wordmark). Generated by extract-assets.js.\n\n";
b += `export const VANNA_SHAPE = ${JSON.stringify(shape)};\n\n`;
b += `export const WORDMARK_PATHS = ${JSON.stringify([...wmBody.matchAll(/d="([^"]+)"/g)].map(x => x[1]))};\n`;
fs.writeFileSync(path.join(app, "src", "generated", "brand.ts"), b);
console.log("png", png.length, "svg", Object.keys(svg).length, "wordmark paths", [...wmBody.matchAll(/d="/g)].length);
